"""`hooks install|uninstall|status`: core.hooksPath -> a kit-owned dir under $SOMNUS_HOME.

Never clobbers: the previous hooks dir (core.hooksPath or .git/hooks) is recorded in chain.json and
every executable hook in it gets a forwarding shim, so commit-msg, pre-push, etc. keep running.
The kit's pre-commit runs `verify --staged` first, then the previous pre-commit if there was one.
"""

from __future__ import annotations

import json
import os
import shlex
import stat
import sys
from pathlib import Path
from typing import Optional

from . import gitio, home

KIT_ROOT = Path(__file__).resolve().parents[1]
MARK = "# generated by somnus-kit hooks install"


def _exe(p: Path) -> bool:
    return p.is_file() and os.access(p, os.X_OK) and not p.name.endswith(".sample")


def _previous_dir(repo: Path, configured: Optional[str]) -> Path:
    if configured:
        p = Path(configured).expanduser()
        return p if p.is_absolute() else (repo / p)
    return gitio.git_dir(repo) / "hooks"


def _write_exec(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _pre_commit(rh: home.RepoHome, prev: Optional[Path]) -> str:
    q = shlex.quote
    libpath = os.environ.get("SOMNUS_KIT_LIBPATH", "")
    chain = (f'if [ -x {q(str(prev))} ]; then exec {q(str(prev))} "$@"; fi\n') if prev else ""
    return f"""#!/bin/sh
{MARK}; repo-id {rh.id}
# Blocks the commit when `somnus-kit verify --staged` reports FAIL (exit 1) or cannot run (exit 2).
# Operator commits of ø/protected files: SOMNUS_KIT_OPERATOR=1 git commit ...
: "${{SOMNUS_HOME:={rh.home}}}"; export SOMNUS_HOME
PYTHONPATH={q(str(KIT_ROOT))}${{PYTHONPATH:+:$PYTHONPATH}}; export PYTHONPATH
{"SOMNUS_KIT_LIBPATH=" + q(libpath) + "; export SOMNUS_KIT_LIBPATH" if libpath else ""}
top=$(git rev-parse --show-toplevel) || exit 2
{q(sys.executable)} -m somnus_kit verify "$top" --staged
rc=$?
if [ $rc -ne 0 ]; then
  echo "somnus-kit: commit blocked (verify exit $rc). Fix the FAIL items above; do not use --no-verify." >&2
  exit $rc
fi
{chain}exit 0
"""


def install(repo: Path, rh: Optional[home.RepoHome] = None) -> dict:
    rh = rh or home.RepoHome(repo)
    rh.ensure("hooks")
    configured = gitio.config_get(repo, "core.hooksPath")
    chain_file = rh.hooks / "chain.json"
    if configured and Path(configured).resolve() == rh.hooks.resolve() and chain_file.is_file():
        chain = json.loads(chain_file.read_text(encoding="utf-8"))  # reinstall: keep the original chain
    else:
        chain = {"previous_hooks_path": configured, "previous_dir": str(_previous_dir(repo, configured))}
    prev_dir = Path(chain["previous_dir"])
    shims = []
    prev_pre_commit = None
    if prev_dir.is_dir() and prev_dir.resolve() != rh.hooks.resolve():
        for h in sorted(prev_dir.iterdir()):
            if not _exe(h):
                continue
            if h.name == "pre-commit":
                prev_pre_commit = h
                continue
            _write_exec(rh.hooks / h.name, f'#!/bin/sh\n{MARK}; forwards to the previous hook\nexec {shlex.quote(str(h))} "$@"\n')
            shims.append(h.name)
    _write_exec(rh.hooks / "pre-commit", _pre_commit(rh, prev_pre_commit))
    chain["shims"] = shims
    chain["chained_pre_commit"] = str(prev_pre_commit) if prev_pre_commit else None
    chain_file.write_text(json.dumps(chain, indent=2) + "\n", encoding="utf-8")
    gitio.config_set(repo, "core.hooksPath", str(rh.hooks))
    return {"hooks_dir": str(rh.hooks), **chain}


def uninstall(repo: Path, rh: Optional[home.RepoHome] = None) -> dict:
    rh = rh or home.RepoHome(repo)
    chain_file = rh.hooks / "chain.json"
    configured = gitio.config_get(repo, "core.hooksPath")
    if not configured or Path(configured).resolve() != rh.hooks.resolve():
        return {"removed": False, "reason": "core.hooksPath is not the kit's hooks dir"}
    chain = json.loads(chain_file.read_text(encoding="utf-8")) if chain_file.is_file() else {}
    prev = chain.get("previous_hooks_path")
    if prev:
        gitio.config_set(repo, "core.hooksPath", prev)
    else:
        gitio.config_unset(repo, "core.hooksPath")
    return {"removed": True, "restored_hooks_path": prev}


def status(repo: Path, rh: Optional[home.RepoHome] = None) -> dict:
    rh = rh or home.RepoHome(repo)
    configured = gitio.config_get(repo, "core.hooksPath")
    on = bool(configured) and Path(configured).resolve() == rh.hooks.resolve() and (rh.hooks / "pre-commit").is_file()
    return {"installed": on, "core.hooksPath": configured, "hooks_dir": str(rh.hooks)}
