"""AGENTS.md marked section and the thin agent adapters, both owned by the kit.

AGENTS.md is canonical. The kit writes only between its markers. Adapters are pointer files
(never copies of AGENTS.md content) and exist only when kit.json enables them.
"""

from __future__ import annotations

import re
from typing import Optional

BEGIN = "<!-- somnus-kit:begin v2 (generated from .somnus-kit/kit.json by `somnus-kit agents`; do not edit inside) -->"
END = "<!-- somnus-kit:end -->"
_REGION = re.compile(r"<!-- somnus-kit:begin[^\n]*-->.*?<!-- somnus-kit:end -->", re.S)

ADAPTERS = {
    "claude": {
        "path": "CLAUDE.md",
        "text": "@AGENTS.md\n\nGenerated by somnus-kit (kit.json adapters.claude). AGENTS.md is canonical; edit it, not this file.\n",
    },
    "copilot": {
        "path": ".github/copilot-instructions.md",
        "text": "Generated by somnus-kit (kit.json adapters.copilot). Follow [AGENTS.md](../AGENTS.md); this file is only a pointer to it.\n",
    },
}


def _bullets(items: list[str], empty: str) -> str:
    return "\n".join(f"- `{i}`" for i in items) if items else f"- {empty}"


def render(manifest: dict) -> str:
    """Section text. Depends only on kit.json, so it is stable until the manifest changes."""
    overrides = manifest.get("roles", {}).get("overrides", {})
    ov = "\n".join(f"- `{p}` is {g}" for p, g in sorted(overrides.items())) or "- none"
    gen = sorted(p for p, m in manifest.get("ownership", {}).items() if m.get("class") == "generated")
    gen += sorted(g["glob"] + f" ({g.get('owner', 'declared')})" for g in manifest.get("generated", []))
    meta = manifest.get("metadata", {})
    meta_line = ("New files that can carry a header get one before commit: `somnus stamp PATH --write` "
                 "(paths excluded in `.somnus.toml` are exempt)." if meta.get("require_on_new", True)
                 else "Metadata headers on new files are not required in this repo.")
    return f"""{BEGIN}
## Repo guard (somnus-kit)

Everything above this section is operator intent. This section is generated from `.somnus-kit/kit.json`.

1. Open a session before you edit: `somnus-kit brief . --task "<the task>"`, plus `--scope <glob>` when the
   operator gave one. Read the context pack it prints and open those files. Do not read the whole tree.
2. Edit inside the declared scope and its impact set (importers, tests, docs it names). Anything else is
   out of scope and fails verify.
3. Before you stop or commit: `somnus-kit verify .`. FAIL means stop and fix or report. WARN means say why.
4. The pre-commit hook runs `somnus-kit verify --staged`. Never bypass it (`--no-verify`, unsetting hooksPath).
5. {meta_line}
6. Session state, models, and baselines live under `$SOMNUS_HOME`. Never write kit state into this repo.
7. Never push, publish, or open a release.

Document roles:
- ø operator (AGENTS, PLAN, TASK, SCOPE): read-only to agents.
- ○ living (ARCHITECTURE_MAP, CONTEXT, DECISIONS, MEMORY, NOTEPAD, STATE): keep current from verified work.
- ♤ public (README, SPEC, ARCHITECTURE, DEVELOPMENT_SETUP, filetree): edits must pass the doc gate.
- A somnus header tag `boundary:operator|living|public` sets the role of any other file.

Role overrides from kit.json:
{ov}

Protected paths (operator only):
{_bullets(sorted(manifest.get('protected', [])), 'none')}

Generated or owned files (never hand-edit; regenerate through the owner):
{_bullets(gen, 'none')}
{END}"""


def extract(text: Optional[str]) -> Optional[str]:
    if text is None:
        return None
    m = _REGION.search(text)
    return m.group(0) if m else None


def strip(text: Optional[str]) -> Optional[str]:
    """AGENTS.md text with the kit region removed (to see whether operator text changed)."""
    if text is None:
        return None
    return _REGION.sub("", text).rstrip() + "\n"


def upsert(text: Optional[str], manifest: dict) -> str:
    section = render(manifest)
    if text is None or not text.strip():
        return "# AGENTS.md\n\n" + section + "\n"
    if _REGION.search(text):
        return _REGION.sub(lambda _m: section, text, count=1)
    return text.rstrip("\n") + "\n\n" + section + "\n"


def enabled(manifest: dict) -> dict[str, dict]:
    flags = manifest.get("adapters", {})
    return {k: v for k, v in ADAPTERS.items() if flags.get(k)}


def adapter_for_path(path: str) -> Optional[str]:
    for k, v in ADAPTERS.items():
        if v["path"] == path:
            return k
    return None
